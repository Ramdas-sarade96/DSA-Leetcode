
class Solution
{
      public int countCommas(int n)
      {
          
          return n-1000+1;
    

      }
}

public class Leetcode3870 
{
    public static void main(String args[])
    {
        Solution s = new Solution();
        int n =100000;
        System.out.println(s.countCommas(n));
    }
    
}
